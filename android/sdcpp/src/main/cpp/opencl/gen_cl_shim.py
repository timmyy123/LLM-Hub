"""Generate cl_shim.cpp: OpenCL entry points that forward to the vendor driver loaded with dlopen.

libllmhub_sdcpp.so must load on every phone, so it cannot list libOpenCL.so as a dependency
(phones without that library would fail System.loadLibrary). ggml's OpenCL backend calls these
forwarders instead; without a vendor driver they return OpenCL errors and the backend reports no
device. Only the functions ggml-opencl uses are generated.

Two additions keep the UI responsive while ggml computes (issue #133: Android reported the app as
not responding during video decoding). clCreateContext asks Adreno drivers for low GPU priority
(cl_qcom_priority_hint), and clEnqueueNDRangeKernel keeps at most two kernels in flight per queue:
ggml enqueues a whole graph at once, and the UI's frames waited on the GPU behind all of it.

Usage: python3 gen_cl_shim.py <ggml/src/ggml-opencl> include/CL/cl.h cl_shim.cpp
"""

import pathlib
import re
import sys


def split_params(params: str):
    out, depth, cur = [], 0, ""
    for ch in params:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return [] if out == ["void"] else out


def param_name(param: str) -> str:
    callback = re.search(r"\(\s*CL_CALLBACK\s*\*\s*(\w+)\s*\)", param)
    if callback:
        return callback.group(1)
    return re.findall(r"\w+", param.split("[")[0])[-1]


def main():
    ggml_dir, header, out = sys.argv[1:4]
    used = set()
    for src in pathlib.Path(ggml_dir).glob("*.[ch]*"):
        used |= set(re.findall(r"\b(cl[A-Z]\w+)\s*\(", src.read_text(errors="ignore")))
    text = pathlib.Path(header).read_text()
    decls = re.findall(r"extern CL_API_ENTRY\s+([\w\s\*]+?)\s+CL_API_CALL\s+(cl\w+)\s*\((.*?)\)\s*CL_API_SUFFIX\w*;",
                       text, re.S)
    lines = [
        "// Generated by gen_cl_shim.py from include/CL/cl.h; do not edit. See gen_cl_shim.py.",
        "#define CL_TARGET_OPENCL_VERSION 300",
        "#include <CL/cl.h>",
        "#include <android/log.h>",
        "#include <dlfcn.h>",
        "#include <cstdlib>",
        "#include <cstring>",
        "#include <deque>",
        "#include <mutex>",
        "#include <string>",
        "#include <unordered_map>",
        "#include <vector>",
        "",
        "namespace {",
        "void* vendor_opencl() {",
        "    static void* handle = [] {",
        "        const char* names[] = {\"libOpenCL.so\", \"libOpenCL-pixel.so\", \"libOpenCL-car.so\",",
        "                               \"/vendor/lib64/libOpenCL.so\", \"/system/vendor/lib64/libOpenCL.so\"};",
        "        for (const char* name : names) {",
        "            if (void* h = dlopen(name, RTLD_NOW | RTLD_LOCAL)) {",
        "                return h;",
        "            }",
        "        }",
        "        return static_cast<void*>(nullptr);",
        "    }();",
        "    return handle;",
        "}",
        "",
        "template <typename F>",
        "F vendor_symbol(const char* name) {",
        "    void* h = vendor_opencl();",
        "    return h != nullptr ? reinterpret_cast<F>(dlsym(h, name)) : nullptr;",
        "}",
        "",
        "// cl_qcom_priority_hint (cl_ext_qcom.h)",
        "constexpr cl_context_properties CONTEXT_PRIORITY_HINT_QCOM = 0x40C9;",
        "constexpr cl_context_properties PRIORITY_HINT_LOW_QCOM     = 0x40CC;",
        "",
        "bool device_has_extension(cl_device_id device, const char* extension) {",
        "    auto get_info = vendor_symbol<decltype(&clGetDeviceInfo)>(\"clGetDeviceInfo\");",
        "    size_t size   = 0;",
        "    if (get_info == nullptr || get_info(device, CL_DEVICE_EXTENSIONS, 0, nullptr, &size) != CL_SUCCESS || size == 0) {",
        "        return false;",
        "    }",
        "    std::string extensions(size, '\\0');",
        "    return get_info(device, CL_DEVICE_EXTENSIONS, size, extensions.data(), nullptr) == CL_SUCCESS &&",
        "           extensions.find(extension) != std::string::npos;",
        "}",
        "",
        "// The caller's context properties plus low GPU priority on Adreno, so the UI and the compositor",
        "// get the GPU between ggml's kernels. LLMHUB_CL_PRIORITY=normal (debug) keeps the driver default.",
        "std::vector<cl_context_properties> low_priority_properties(const cl_context_properties* properties, cl_uint num_devices,",
        "                                                           const cl_device_id* devices) {",
        "    std::vector<cl_context_properties> out;",
        "    bool has_hint = false;",
        "    for (const cl_context_properties* p = properties; p != nullptr && p[0] != 0; p += 2) {",
        "        out.push_back(p[0]);",
        "        out.push_back(p[1]);",
        "        has_hint |= p[0] == CONTEXT_PRIORITY_HINT_QCOM;",
        "    }",
        "    const char* mode = getenv(\"LLMHUB_CL_PRIORITY\");",
        "    bool keep_default = mode != nullptr && strcmp(mode, \"normal\") == 0;",
        "    if (!has_hint && !keep_default && num_devices > 0 && device_has_extension(devices[0], \"cl_qcom_priority_hint\")) {",
        "        out.push_back(CONTEXT_PRIORITY_HINT_QCOM);",
        "        out.push_back(PRIORITY_HINT_LOW_QCOM);",
        "        __android_log_print(ANDROID_LOG_INFO, \"SdCppJni\", \"OpenCL context at low GPU priority\");",
        "    }",
        "    out.push_back(0);",
        "    return out;",
        "}",
        "",
        "// ggml enqueues a whole graph at once, and the GPU ran the UI's frames only after the kernels",
        "// queued before them: seconds of video kernels per graph, so the UI missed frames for over 10 s.",
        "// Waiting for the kernel two back keeps the GPU busy while a UI frame waits for at most the two",
        "// kernels ahead of it. LLMHUB_CL_PACE=0 (debug) turns this off.",
        "constexpr size_t MAX_KERNELS_IN_FLIGHT = 2;",
        "",
        "void pace_kernel(cl_command_queue queue, cl_event event) {",
        "    static std::mutex mutex;",
        "    static std::unordered_map<cl_command_queue, std::deque<cl_event>> in_flight;",
        "    static auto wait_for = vendor_symbol<decltype(&clWaitForEvents)>(\"clWaitForEvents\");",
        "    static auto release  = vendor_symbol<decltype(&clReleaseEvent)>(\"clReleaseEvent\");",
        "    cl_event oldest      = nullptr;",
        "    {",
        "        std::lock_guard<std::mutex> lock(mutex);",
        "        auto& events = in_flight[queue];",
        "        events.push_back(event);",
        "        if (events.size() <= MAX_KERNELS_IN_FLIGHT) {",
        "            return;",
        "        }",
        "        oldest = events.front();",
        "        events.pop_front();",
        "    }",
        "    wait_for(1, &oldest);  // also flushes the queue",
        "    release(oldest);",
        "}",
        "",
        "bool pacing_enabled() {",
        "    static const bool enabled = [] {",
        "        const char* mode = getenv(\"LLMHUB_CL_PACE\");",
        "        return mode == nullptr || strcmp(mode, \"0\") != 0;",
        "    }();",
        "    return enabled;",
        "}",
        "}  // namespace",
        "",
        "extern \"C\" {",
    ]
    generated = []
    for ret, name, params in decls:
        if name not in used or name in generated:
            continue
        ret = " ".join(ret.split())
        plist = split_params(" ".join(params.split()))
        names = [param_name(p) for p in plist]
        if ret == "cl_int":
            fail = "return -1001;  /* CL_PLATFORM_NOT_FOUND_KHR: ggml then reports no OpenCL device */" if name == "clGetPlatformIDs" else "return CL_INVALID_PLATFORM;"
        else:
            fail = ("if (errcode_ret != nullptr) { *errcode_ret = CL_INVALID_PLATFORM; } " if "errcode_ret" in names else "") + "return nullptr;"
        body = [f"    return fn({', '.join(names)});"]
        if name == "clCreateContext":
            body = ["    auto props = low_priority_properties(properties, num_devices, devices);",
                    f"    cl_context context = fn({', '.join(['props.data()'] + names[1:])});",
                    "    // A driver that rejects the hint still gets a context at its default priority.",
                    f"    return context != nullptr ? context : fn({', '.join(names)});"]
        if name == "clEnqueueNDRangeKernel":
            body = ["    if (!pacing_enabled()) {",
                    f"        return fn({', '.join(names)});",
                    "    }",
                    "    static auto retain = vendor_symbol<decltype(&clRetainEvent)>(\"clRetainEvent\");",
                    "    cl_event own = nullptr;",
                    f"    cl_int err = fn({', '.join(names[:-1] + ['event != nullptr ? event : &own'])});",
                    "    if (err == CL_SUCCESS && event != nullptr && *event != nullptr && retain(*event) == CL_SUCCESS) {",
                    "        pace_kernel(command_queue, *event);",
                    "    } else if (err == CL_SUCCESS && own != nullptr) {",
                    "        pace_kernel(command_queue, own);",
                    "    }",
                    "    return err;"]
        lines += [
            f"CL_API_ENTRY {ret} CL_API_CALL {name}({', '.join(plist) or 'void'}) {{",
            f"    static auto fn = vendor_symbol<decltype(&{name})>(\"{name}\");",
            f"    if (fn == nullptr) {{ {fail} }}",
            *body,
            "}",
            "",
        ]
        generated.append(name)
    lines.append("}  // extern \"C\"")
    missing = sorted(used - set(generated))
    pathlib.Path(out).write_text("\n".join(lines) + "\n")
    print(f"{out}: {len(generated)} functions; not in cl.h (ignored): {missing}")


if __name__ == "__main__":
    main()
